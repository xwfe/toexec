//! gld 与 ccnm 共用的原子文件替换。
//!
//! 这个仓库（`toexec`）一个 crate 管一件事：这里只管「把新内容安全地顶替到
//! 一个已有文件上」。**临时文件叫什么、备份怎么编排、失败之后怎么回滚，都不
//! 在这里**——两个产品的回滚编排差很多（ccnm 按操作类型分并写 journal，gld
//! 一刀切恢复），共享它们只会做出一个全是开关的东西。
//!
//! 共享的是下面这两步纯机制，两边原来各写了一遍，而且写得不一样好：
//!
//! ```text
//! write_durable(temp, 新内容, 原权限)   内容落盘之后才返回
//! replace(temp, 目标)                   一次 rename 顶替
//! ```
//!
//! **一个已知边界**：`rename` 本身是原子的，但「rename 这件事」要在断电后
//! 仍然可见，还得 fsync 目标的**父目录**。这里没做，跟两个产品原来的行为
//! 一致。要补的话是另一个决定，因为它给每次替换再加一次 fsync。

mod atomic;

pub use atomic::{Step, WriteError, replace, write_durable};
